import { polygonToPathD, transformShapeToSheet } from "./geometry";
import type { NestSettings, NestSnapshot, Polygon, Shape } from "./types";

export function download(filename: string, content: string, mime = "text/plain;charset=utf-8"): void {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}

export interface SvgExportOptions {
  hairlineMode?: boolean;
  includeCutOrder?: boolean;
  includeMarginGuide?: boolean;
}

/**
 * Exports a single nested sheet to production SVG with exact physical `mm` units
 * and CorelDRAW-compatible layers (`Inner_Holes` cut first in Blue, `Outer_Cut` in Red).
 */
export function sheetToSVG(
  shapes: Shape[],
  snap: NestSnapshot,
  sheetIdx: number,
  st: NestSettings,
  opts: SvgExportOptions = {}
): string {
  const { hairlineMode = true, includeCutOrder = false, includeMarginGuide = true } = opts;
  const shapeById = new Map(shapes.map((s) => [s.id, s]));
  const placements = snap.placements
    .filter((p) => p.sheet === sheetIdx)
    .sort((a, b) => (a.cutOrder || 0) - (b.cutOrder || 0));

  const strokeWidth = hairlineMode ? "0.0762" : "0.25"; // 0.0762mm = 0.003 in CorelDRAW Hairline

  const holePaths: string[] = [];
  const outerPaths: string[] = [];
  const labels: string[] = [];

  for (let i = 0; i < placements.length; i++) {
    const p = placements[i];
    const sh = shapeById.get(p.shapeId);
    if (!sh) continue;
    const tr = transformShapeToSheet(sh, p.x, p.y, p.angle);

    for (const h of tr.holes) {
      const hd = polygonToPathD(h);
      holePaths.push(
        `    <path d="${hd}" fill="none" stroke="#0066ff" stroke-width="${strokeWidth}" />`
      );
    }

    const od = polygonToPathD(tr.outer, hairlineMode ? [] : tr.holes);
    outerPaths.push(
      `    <path id="part_${i + 1}" d="${od}" fill="${hairlineMode ? "none" : sh.color + "33"}" fill-rule="evenodd" stroke="${hairlineMode ? "#ff0000" : sh.color}" stroke-width="${strokeWidth}" />`
    );

    if (includeCutOrder) {
      const cx = (tr.bbox.minX + tr.bbox.maxX) / 2;
      const cy = (tr.bbox.minY + tr.bbox.maxY) / 2;
      labels.push(
        `    <text x="${cx.toFixed(2)}" y="${cy.toFixed(2)}" font-size="4" text-anchor="middle" dominant-baseline="central" fill="#0f172a">${p.cutOrder || i + 1}</text>`
      );
    }
  }

  const marginRect =
    includeMarginGuide && st.margin > 0
      ? `  <rect id="Safe_Margin" x="${st.margin}" y="${st.margin}" width="${st.sheetW - st.margin * 2}" height="${st.sheetH - st.margin * 2}" fill="none" stroke="#94a3b8" stroke-width="0.15" stroke-dasharray="2,2" />\n`
      : "";

  return [
    `<?xml version="1.0" encoding="UTF-8"?>`,
    `<!-- Generated by NestPro Studio for CorelDRAW / Illustrator / CNC (${st.sheetW}x${st.sheetH} mm) -->`,
    `<svg xmlns="http://www.w3.org/2000/svg" width="${st.sheetW}mm" height="${st.sheetH}mm" viewBox="0 0 ${st.sheetW} ${st.sheetH}">`,
    `  <g id="Sheet_Border">`,
    `    <rect x="0" y="0" width="${st.sheetW}" height="${st.sheetH}" fill="none" stroke="#334155" stroke-width="0.25" />`,
    marginRect ? marginRect.trimEnd() : "",
    `  </g>`,
    `  <g id="Layer_1_Inner_Holes_CutFirst">`,
    ...holePaths,
    `  </g>`,
    `  <g id="Layer_2_Outer_Contours">`,
    ...outerPaths,
    `  </g>`,
    ...(labels.length ? [`  <g id="Layer_3_Cut_Sequence">`, ...labels, `  </g>`] : []),
    `</svg>`,
  ].join("\n");
}

/**
 * Exports all nested sheets side-by-side in a single multi-sheet SVG file.
 */
export function allSheetsToSVG(shapes: Shape[], snap: NestSnapshot, st: NestSettings): string {
  const shapeById = new Map(shapes.map((s) => [s.id, s]));
  const gap = 30;
  const totalW = snap.sheets * st.sheetW + Math.max(0, snap.sheets - 1) * gap;
  const totalH = st.sheetH;

  const groups: string[] = [];
  for (let s = 0; s < snap.sheets; s++) {
    const ox = s * (st.sheetW + gap);
    const sheetItems: string[] = [
      `    <rect x="${ox}" y="0" width="${st.sheetW}" height="${st.sheetH}" fill="none" stroke="#334155" stroke-width="0.3" />`,
    ];
    const pls = snap.placements.filter((p) => p.sheet === s);
    for (const p of pls) {
      const sh = shapeById.get(p.shapeId);
      if (!sh) continue;
      const tr = transformShapeToSheet(sh, ox + p.x, p.y, p.angle);
      for (const h of tr.holes) {
        sheetItems.push(
          `    <path d="${polygonToPathD(h)}" fill="none" stroke="#0066ff" stroke-width="0.0762" />`
        );
      }
      sheetItems.push(
        `    <path d="${polygonToPathD(tr.outer)}" fill="none" stroke="#ff0000" stroke-width="0.0762" />`
      );
    }
    groups.push(`  <g id="Sheet_${s + 1}">\n${sheetItems.join("\n")}\n  </g>`);
  }

  return [
    `<?xml version="1.0" encoding="UTF-8"?>`,
    `<svg xmlns="http://www.w3.org/2000/svg" width="${totalW}mm" height="${totalH}mm" viewBox="0 0 ${totalW} ${totalH}">`,
    ...groups,
    `</svg>`,
  ].join("\n");
}

/**
 * Exports a nested sheet to AutoCAD R12/2000 DXF format (in millimeters) with separate layers:
 * - `SHEET_BORDER` (Color 7 White/Black)
 * - `INNER_HOLES` (Color 5 Blue — cut first)
 * - `OUTER_CUT` (Color 1 Red — cut second)
 * Compatible directly with CorelDRAW, RDWorks, LightBurn, AutoCAD, and CypCut.
 */
export function sheetToDXF(
  shapes: Shape[],
  snap: NestSnapshot,
  sheetIdx: number,
  st: NestSettings
): string {
  const shapeById = new Map(shapes.map((s) => [s.id, s]));
  const placements = snap.placements
    .filter((p) => p.sheet === sheetIdx)
    .sort((a, b) => (a.cutOrder || 0) - (b.cutOrder || 0));

  const out: string[] = [
    "0",
    "SECTION",
    "2",
    "HEADER",
    "9",
    "$INSUNITS",
    "70",
    "4", // 4 = Millimeters
    "0",
    "ENDSEC",
    "0",
    "SECTION",
    "2",
    "ENTITIES",
  ];

  const writeClosedPolyline = (pts: Polygon, layer: string, colorCode: number) => {
    if (pts.length < 3) return;
    out.push(
      "0",
      "POLYLINE",
      "8",
      layer,
      "62",
      String(colorCode),
      "66",
      "1",
      "70",
      "1" // Closed polyline flag
    );
    for (const pt of pts) {
      // Flip Y so bottom-left of sheet is (0,0) in CAD coordinates
      const cadX = pt.x.toFixed(4);
      const cadY = (st.sheetH - pt.y).toFixed(4);
      out.push("0", "VERTEX", "8", layer, "10", cadX, "20", cadY, "30", "0.0");
    }
    out.push("0", "SEQEND");
  };

  // Sheet border
  writeClosedPolyline(
    [
      { x: 0, y: 0 },
      { x: st.sheetW, y: 0 },
      { x: st.sheetW, y: st.sheetH },
      { x: 0, y: st.sheetH },
    ],
    "SHEET_BORDER",
    7
  );

  // Inner holes first (Blue = 5), then Outer contours (Red = 1)
  for (const p of placements) {
    const sh = shapeById.get(p.shapeId);
    if (!sh) continue;
    const tr = transformShapeToSheet(sh, p.x, p.y, p.angle);
    for (const h of tr.holes) {
      writeClosedPolyline(h, "INNER_HOLES", 5);
    }
    writeClosedPolyline(tr.outer, "OUTER_CUT", 1);
  }

  out.push("0", "ENDSEC", "0", "EOF");
  return out.join("\r\n");
}

/**
 * Exports a nested sheet to HPGL (.plt) plotter/cutter format (1 mm = 40 plotter units).
 */
export function sheetToHPGL(
  shapes: Shape[],
  snap: NestSnapshot,
  sheetIdx: number,
  st: NestSettings
): string {
  const SCALE = 40; // Standard HPGL: 40 units per millimeter
  const shapeById = new Map(shapes.map((s) => [s.id, s]));
  const placements = snap.placements
    .filter((p) => p.sheet === sheetIdx)
    .sort((a, b) => (a.cutOrder || 0) - (b.cutOrder || 0));

  const cmds: string[] = ["IN;", "SP1;"];

  const plotRing = (pts: Polygon) => {
    if (pts.length < 2) return;
    const x0 = Math.round(pts[0].x * SCALE);
    const y0 = Math.round((st.sheetH - pts[0].y) * SCALE);
    cmds.push(`PU${x0},${y0};`);
    const coords: string[] = [];
    for (let i = 1; i < pts.length; i++) {
      coords.push(
        `${Math.round(pts[i].x * SCALE)},${Math.round((st.sheetH - pts[i].y) * SCALE)}`
      );
    }
    coords.push(`${x0},${y0}`);
    cmds.push(`PD${coords.join(",")};`);
  };

  for (const p of placements) {
    const sh = shapeById.get(p.shapeId);
    if (!sh) continue;
    const tr = transformShapeToSheet(sh, p.x, p.y, p.angle);
    // Cut holes first
    for (const h of tr.holes) plotRing(h);
    // Then outer contour
    plotRing(tr.outer);
  }

  cmds.push("PU0,0;", "SP0;");
  return cmds.join("\n");
}
